const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {webcrypto}=require('node:crypto');
const root=path.resolve(__dirname,'..');
const context={crypto:webcrypto,URLSearchParams,localStorage:{getItem:()=>null,setItem:()=>{}},document:{getElementById:()=>({textContent:'',value:'',hidden:false}),querySelectorAll:()=>[]}};
vm.createContext(context);
const load=file=>fs.readFileSync(path.join(root,'dist',file),'utf8');
const studio=load('studio.js').split("$('close').onclick=")[0];
vm.runInContext(load('curriculum.js')+load('poetry-data.js')+load('library.js')+studio+`
activeStudioTab=()=>{};refreshCredits=()=>{};studioMessage=()=>{};
this.api={normalize:normalizeStudioRecord,importData:importStudioData,state:()=>studioState,escape:escapeHtml};`,context);
const api=context.api;
const good={id:'test-card',poemId:'lb-lushan',mode:'image',title:'飞瀑构思',alias:'演示同学',prompt:'以“银河落九天”为依据，用水墨表现飞瀑与云雾的想象联系。',evidence:'银河落九天',imagination:'天上与人间的视觉过渡',artifactText:'',createdAt:new Date().toISOString(),feedback:['请说明你的文本依据。']};
assert.equal(api.normalize({...good,mode:'constructor'}),null);
assert.equal(api.normalize({...good,poemId:'unknown'}),null);
assert.equal(api.normalize({...good,prompt:'x'.repeat(5000)}).prompt.length,1800);
assert.equal(api.escape('<img src=x onerror=alert(1)>'),'&lt;img src=x onerror=alert(1)&gt;');
const pack=works=>JSON.stringify({kind:'shixing-poetry-studio',version:1,mode:'demo',works});
assert.throws(()=>api.importData(pack([good,{...good,mode:'constructor'}])));
assert.equal(api.state().works.length,0,'invalid bundles must not partially import');
assert.equal(api.importData(pack([good])),1);
assert.equal(api.state().credits,20,'imported cards must not change demo credits');
assert.equal(api.state().works[0].origin,'imported');
assert.notEqual(api.state().works[0].id,good.id,'imports receive a fresh local identity');
assert.equal(api.state().works[0].prompt,good.prompt);
assert.throws(()=>api.importData(pack(Array.from({length:31},()=>good))));
assert.equal(api.state().works.length,1,'oversized bundles must not change saved cards');
assert.equal(api.normalize({...good,feedback:['<script>evil()</script>']}).feedback[0],'<script>evil()</script>');
console.log('Studio: validated import, atomic rejection, quota isolation, bounded input, and escaped content passed.');
